mod tests {
    use super::*;

    #[test]
    fn test_ordenacao_estrita_tabela_canonica() {
        for w in TABELA_CANONICA.windows(2) {
            assert!(
                w[0].0 < w[1].0,
                "A tabela de léxico não está ordenada: '{}' >= '{}'",
                w[0].0,
                w[1].0
            );
        }
    }
}
